export type TsKey = keyof typeof en;

export function useTs() {
  const { lang } = useI18n();
  return useMemo(() => {
    const d: Dict = lang === "am" ? am : (en as Dict);
    const f = (key: TsKey, vars: Record<string, string | number> = {}) =>
      d[key].replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`));
    /** Pick `${base}One` or `${base}Other` and fill {n}. */
    const n = (base: string, count: number) => {
      const key = `${base}${count === 1 ? "One" : "Other"}` as TsKey;
      return f(key, { n: count });
    };
    return { ...d, f, n, lang };
  }, [lang]);
}
